"""
Builds spfx/app/styles.ts from website/src/styles.css for the SharePoint web part:
every rule is scoped under .mailroom-root so nothing leaks into the SharePoint
page, keyframes get an mr- prefix, dark mode is dropped (SharePoint pages are
light), and a few page-level rules are adjusted. Run from the repository root:
    python3 spfx/tools/scope-css.py
"""
import json
import re
import sys

ROOT = '.mailroom-root'
src = open('website/src/styles.css', encoding='utf-8').read()
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)


def parse(text, i=0):
    """Returns (nodes, index). Nodes: ('rule', selector, body) or ('at', prelude, children|None, body)."""
    nodes = []
    buf = ''
    while i < len(text):
        ch = text[i]
        if ch == '{':
            head = buf.strip()
            buf = ''
            if head.startswith('@'):
                name = head.split()[0]
                if name in ('@media', '@supports', '@layer', '@container'):
                    children, i = parse(text, i + 1)
                    nodes.append(('at', head, children, None))
                    continue
                body, i = block(text, i + 1)
                nodes.append(('at', head, None, body))
                continue
            body, i = block(text, i + 1)
            nodes.append(('rule', head, body))
            continue
        if ch == '}':
            return nodes, i + 1
        buf += ch
        i += 1
    return nodes, i


def block(text, i):
    depth = 1
    start = i
    while depth:
        if text[i] == '{':
            depth += 1
        elif text[i] == '}':
            depth -= 1
        i += 1
    return text[start:i - 1], i


nodes, _ = parse(src)

keyframes = set()


def collect(ns):
    for n in ns:
        if n[0] == 'at':
            if n[1].startswith('@keyframes'):
                keyframes.add(n[1].split()[1])
            elif n[2]:
                collect(n[2])


collect(nodes)


def rename_animations(body):
    def fix(m):
        value = m.group(2)
        for k in keyframes:
            value = re.sub(rf'(?<![\w-]){re.escape(k)}(?![\w-])', f'mr-{k}', value)
        return m.group(1) + value
    return re.sub(r'(animation(?:-name)?\s*:)([^;]*)', fix, body)


def scope_selector(sel):
    out = []
    for part in [p.strip() for p in sel.split(',')]:
        if not part:
            continue
        if part.startswith('::view-transition'):
            out.append(part)
        elif part in (':root', 'body'):
            out.append(ROOT)
        elif part == 'html':
            continue
        else:
            out.append(f'{ROOT} {part}')
    return ', '.join(out)


def emit(ns, indent=''):
    lines = []
    for n in ns:
        if n[0] == 'rule':
            sel = scope_selector(n[1])
            if not sel:
                continue
            body = rename_animations(n[2])
            if n[1].strip() == 'body':
                body = re.sub(r'\s*min-height:\s*100vh;', '', body)
            lines.append(f'{indent}{sel} {{{body}}}')
        else:
            prelude, children, body = n[1], n[2], n[3]
            if prelude.startswith('@media') and 'prefers-color-scheme: dark' in prelude:
                continue
            if prelude.startswith('@keyframes'):
                name = prelude.split()[1]
                lines.append(f'{indent}@keyframes mr-{name} {{{body}}}')
            elif children is not None:
                lines.append(f'{indent}{prelude} {{\n{emit(children, indent + "  ")}\n{indent}}}')
            else:
                lines.append(f'{indent}{prelude} {{{body}}}')
    return '\n'.join(lines)


css = emit(nodes)
css += f"""

/* In SharePoint: no full-window screens, the page scrolls itself, and no extra outline. */
{ROOT} {{ min-height: 0; color-scheme: light; }}
{ROOT} .app {{ min-height: 0; }}
{ROOT} .boot, {ROOT} .fatal {{ min-height: 440px; }}
{ROOT} .setup-page {{ padding-top: 24px; }}
{ROOT} .bar {{ top: 0; }}
"""

assert ':root' not in css and 'prefers-color-scheme: dark' not in css
out = '/* eslint-disable */\n// Generated by spfx/tools/scope-css.py from website/src/styles.css. Do not edit by hand.\n\n'
out += 'export const MAIL_ROOM_CSS = ' + json.dumps(css, ensure_ascii=False) + ';\n'
open('spfx/app/styles.ts', 'w', encoding='utf-8').write(out)
print(f'{len(css)} chars, {len(keyframes)} keyframes renamed:', ', '.join(sorted(keyframes)))
